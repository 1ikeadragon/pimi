// Writes the block formats into the pimi-visualize skill's SKILL.md, between the markers, from the
// same constants the block parsers use, so the skill and the parsers cannot disagree. Runs after tsc
// in the protocol build. They live in SKILL.md itself: a separate file costs the agent an extra Read.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { PIMI_VISUALIZATION_INSTRUCTIONS } = await import(
  pathToFileURL(resolve(packageRoot, "dist/chat-visualization.js")).href
);
const output = resolve(packageRoot, "../../skills/pimi-visualize/SKILL.md");
const start =
  "<!-- formats:start (generated by packages/protocol/scripts/generate-visualize-formats.mjs; do not edit) -->";
const end = "<!-- formats:end -->";
const source = await readFile(output, "utf8");
const from = source.indexOf("<!-- formats:start");
const to = source.indexOf(end);
if (from === -1 || to === -1 || to < from) {
  throw new Error(`SKILL.md must contain the ${end} and formats:start markers`);
}
const block = `${start}\n\n${PIMI_VISUALIZATION_INSTRUCTIONS.trim()}\n\n${end}`;
await writeFile(output, source.slice(0, from) + block + source.slice(to + end.length));
console.log("generated the formats in skills/pimi-visualize/SKILL.md");
